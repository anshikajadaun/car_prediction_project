#liberary import
import pandas as pd # tabular
import numpy as np # numeric
import matplotlib.pyplot as plt # visualization
from sklearn.model_selection import train_test_split # its a module
from sklearn.linear_model import LinearRegression #for linear regression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score #for errors
print("the libraries are import")

# PART B- Dataset Setup
#step 1
df=pd.read_csv("car_prediction_project.csv") # read the data
print(df.head())

# step 2 inspect the dataset
print("first five rows")
print(df.head())

print("\nDataset shape:")
print(df.shape)

print("\ncolumn names:")
print(df.columns)

print("\nDataset information ")
df.info()

print("\nStatistical summary:")
print(df.describe())

print("Missing values")
print(df.isnull().sum())

print("\nDuplicate row:")
print(df.duplicated().sum())

plt.figure(figsize= (8,5))
plt.scatter(df["Engine Size"],df["Price"])
plt.xlabel("Engine Size-->")
plt.ylabel("Price-->")
plt.title("Engine Size vs price")
plt.grid(True)
plt.show()

#attendance vs Marks
plt.figure(figsize=(8,5))
plt.scatter(df['Year'],df['Engine Size'])
plt.xlabel("Year(%)--->")
plt.ylabel("Engine Size--->")
plt.title("Year vs Engine Size")
plt.grid(True)
plt.show()

#Saperate Features and Target
x=df[["Engine Size","Year","Mileage"]]
y=df["Price"]

print("Features(X):")
print(x)
print("\nTarget(Y):")
print(y)

#split of train testing
x_train, x_test, y_train, y_test = train_test_split(
    x,
    y,
    test_size=0.2,
    random_state=42
    )

print("Training samples :", len(x_train))
print("Testing samples :",  len(x_test))

# building and creating the linear regression model
# step:1- create the model

model = LinearRegression()

# train the model
model.fit(x_train, y_train)

#Inspect Learned Parameters
print("cofficients:")
print(model.coef_)
print("\nIntercepts:")
print(model.intercept_)

#Prediction
#pridict the test data
y_pred=model.predict(x_test)

print("Actual Price:")

print(y_test.values)

print("\nPredicted Price:")

print(y_pred)

camparison =pd.DataFrame({
    "Actual Price":y_test.values,
    "Predicted Price":y_pred
})
print(camparison)

# mean absolute error(MAE)
mae=mean_absolute_error(y_test,y_pred)
print("Mean Absolute Error:",mae)

mse=mean_squared_error(y_test,y_pred)
print("Mean Squared Error:",mse)

#R2 Score
r2=r2_score(y_test,y_pred)
print("R2 Score:",r2)

print("X column")
print( x.columns.tolist())
print("\nTraining Samples:")
print(x_train.columns.tolist())

# Create new car data in the correct order
new_price = pd.DataFrame({
    "Engine Size" : [2.3],
    "Year": [2022],
    "Mileage":[114832],
})
# Predict car price
Predicted_Price = model.predict(new_price)

# Display result
print("Engine Size", new_price["Engine Size"].iloc[0])
print("Year:", new_price["Year"].iloc[0])
print("Mileage:", new_price["Mileage"].iloc[0])
print("Predicted Price:", round(Predicted_Price[0], 2))

import joblib
import sklearn

# Save the train data
joblib.dump(model, "car_prediction_project.pkl")

#Check the installed scikit-learn version
print("scikit-learn version:", sklearn.__version__)
print("Model saved successfully!")

